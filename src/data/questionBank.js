/**
 * Returns a randomized batch of questions from the bank, filtered optionally by category.
 */
export function getRandomQuestions(category = "all", count = 10) {
  let pool = [...QUESTION_BANK];

  if (category && category !== "all") {
    const filtered = pool.filter((q) => q.category === category);
    if (filtered.length > 0) {
      pool = filtered;
    }
  }

  // Shuffle pool (Fisher-Yates)
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  // Pick count items
  const selected = pool.slice(0, Math.min(count, pool.length));

  // Clone with unique IDs and shuffled options so each fetch feels fresh
  return selected.map((q, idx) => {
    const uniqueId = `bank_${q.category}_${Date.now()}_${idx}_${Math.random().toString(36).substring(2, 6)}`;
    const allOptions = [...(q.options || [...q.incorrectAnswers, q.correctAnswer])];

    // Shuffle options
    for (let i = allOptions.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [allOptions[i], allOptions[j]] = [allOptions[j], allOptions[i]];
    }

    const wrongOptions = allOptions.filter((opt) => opt !== q.correctAnswer);

    return {
      id: uniqueId,
      category: q.category,
      question: { text: q.questionText || q.question.text },
      questionText: q.questionText || q.question.text,
      correctAnswer: q.correctAnswer,
      incorrectAnswers: wrongOptions,
      options: allOptions,
    };
  });
}
